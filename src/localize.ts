const TRANSLATIONS: Record<string, Table> = { en, de };

export function baseLanguage(locale: string | undefined): string {
  const base = (locale ?? "en").split("-")[0].toLowerCase();
  return TRANSLATIONS[base] ? base : "en";
}

export function localize(key: string, locale?: string, vars?: Record<string, string>): string {
  const table = TRANSLATIONS[baseLanguage(locale)];
  let text = table[key] ?? en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) text = text.replace(`{${k}}`, v);
  return text;
}

